    """Returns official schema expectations for user-provided CSV and GeoJSON datasets."""
    schema_path = "data/sample/sample_schema.json"
    if os.path.exists(schema_path):
        with open(schema_path, "r", encoding="utf-8") as f:
            return json.load(f)
