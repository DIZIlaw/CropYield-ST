class RealIngestionRequest(BaseModel):
    start_date: str = Field(default="2025-10-15")
    end_date: str = Field(default="2026-04-15")
    cloud_max_percent: float = Field(default=30.0, ge=0.0, le=100.0)
    study_area_name: str = Field(default="live_study_area")


@router.post("/datasets/real-ingestion")
def ingest_real_satellite_data(req: RealIngestionRequest):
    """
    Triggers genuine satellite data extraction for the active study area geometries.
    Refuses with diagnostic feedback if external provider credentials are missing.
    """
    from backend.app.data.real_data_pipeline import real_data_pipeline
    if storage.gdf is None or len(storage.gdf) == 0:
        raise HTTPException(status_code=400, detail="No active parcel geometries loaded.")
        
    try:
        res = real_data_pipeline.ingest_real_satellite_observations(
            gdf=storage.gdf,
            start_date=req.start_date,
            end_date=req.end_date,
            study_area_name=req.study_area_name,
            cloud_max_percent=req.cloud_max_percent
        )
        return res
    except PermissionError as pe:
        raise HTTPException(status_code=403, detail=str(pe))
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
