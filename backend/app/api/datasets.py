@router.post("/datasets/validate")
async def validate_dataset(
    geojson_file: Optional[UploadFile] = File(None),
    timeseries_file: Optional[UploadFile] = File(None),
    labels_file: Optional[UploadFile] = File(None)
):
    """
    Validates uploaded files against CropYield-ST format, CRS, and column requirements.
    Provides actionable diagnostics.
    """
    errors = []
    warnings = []
    info = {}
    
    # Validate GeoJSON
    if geojson_file is not None:
        try:
            content = await geojson_file.read()
            geojson_data = json.loads(content.decode("utf-8"))
            if "features" not in geojson_data or len(geojson_data["features"]) == 0:
                errors.append("GeoJSON file must contain a 'features' array with at least 1 feature.")
            else:
                sample_feat = geojson_data["features"][0]
                props = sample_feat.get("properties", {})
                if "parcel_id" not in props and "id" not in props:
                    warnings.append("GeoJSON feature properties do not contain 'parcel_id'. ID will be autogenerated.")
                info["geojson_features_count"] = len(geojson_data["features"])
        except Exception as e:
            errors.append(f"Invalid GeoJSON file: {str(e)}")
            
    # Validate Timeseries CSV
    if timeseries_file is not None:
        try:
            content = await timeseries_file.read()
            import io
            df = pd.read_csv(io.BytesIO(content))
            required_cols = ["parcel_id", "date", "ndvi"]
            missing = [c for c in required_cols if c not in df.columns]
            if missing:
                errors.append(f"Timeseries CSV missing required columns: {missing}")
            else:
                info["timeseries_rows_count"] = len(df)
                info["timeseries_unique_parcels"] = df["parcel_id"].nunique()
                info["timeseries_date_range"] = [str(df["date"].min()), str(df["date"].max())]
                
            # Check for radar
            radar_cols = [c for c in ["sar_vv_linear", "sar_vv_db", "sar_vh_db"] if c in df.columns]
            if not radar_cols:
                warnings.append("No Sentinel-1 SAR columns found. Will fall back to optical-only mode.")
        except Exception as e:
            errors.append(f"Invalid Timeseries CSV file: {str(e)}")
            
    # Validate Labels CSV
    if labels_file is not None:
        try:
            content = await labels_file.read()
            import io
            df = pd.read_csv(io.BytesIO(content))
            if "parcel_id" not in df.columns or "yield_tha" not in df.columns:
                errors.append("Yield Labels CSV must contain 'parcel_id' and 'yield_tha' columns.")
            else:
                info["labels_count"] = len(df)
                info["mean_label_yield"] = round(float(df["yield_tha"].mean()), 2)
        except Exception as e:
            errors.append(f"Invalid Labels CSV file: {str(e)}")
            
    is_valid = len(errors) == 0
    return {
        "valid": is_valid,
        "errors": errors,
        "warnings": warnings,
        "metadata": info
    }


